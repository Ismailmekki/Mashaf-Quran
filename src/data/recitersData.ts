export function getAyahAudioUrl(
  reciterOrFolder: Reciter | string,
  surahNumber: number,
  ayahNumberInSurah: number,
  globalAyahNumber?: number
): string {
  const surahFormatted = String(surahNumber).padStart(3, "0");
  const ayahFormatted = String(ayahNumberInSurah).padStart(3, "0");

  if (typeof reciterOrFolder === "string") {
    // If it is Islamic Network ID
    if (reciterOrFolder.startsWith("ar.")) {
      const globalNum = globalAyahNumber || 1;
      return `https://cdn.islamic.network/quran/audio/128/${reciterOrFolder}/${globalNum}.mp3`;
    }
    // If it is Wadi Al Yamani special folder
    if (reciterOrFolder === "wdee3") {
      return `https://server6.mp3quran.net/wdee3/${surahFormatted}.mp3`;
    }
    return `https://everyayah.com/data/${reciterOrFolder}/${surahFormatted}${ayahFormatted}.mp3`;
  }

  const reciter = reciterOrFolder;

  // If reciter is surah-format only (e.g. Wadee Al Yamani, Hazza Al Balushi, etc.)
  if (reciter.format === "surah" && reciter.surahAudioServer) {
    return `${reciter.surahAudioServer}${surahFormatted}.mp3`;
  }

  // Priority 1: Islamic Network CDN if available and globalAyahNumber is passed
  if (reciter.islamicNetworkId && globalAyahNumber) {
    return `https://cdn.islamic.network/quran/audio/128/${reciter.islamicNetworkId}/${globalAyahNumber}.mp3`;
  }

  // Priority 2: EveryAyah verified folder
  if (reciter.serverFolder && reciter.serverFolder !== "wdee3") {
    return `https://everyayah.com/data/${reciter.serverFolder}/${surahFormatted}${ayahFormatted}.mp3`;
  }

  // Default fallback to Alafasy EveryAyah
  return `https://everyayah.com/data/Alafasy_128kbps/${surahFormatted}${ayahFormatted}.mp3`;
}

export function getSurahAudioUrl(surahNumber: number, reciter: Reciter): string {
  const surahFormatted = String(surahNumber).padStart(3, "0");
  if (reciter.surahAudioServer) {
    return `${reciter.surahAudioServer}${surahFormatted}.mp3`;
  }
  return `https://server8.mp3quran.net/afs/${surahFormatted}.mp3`;
}
